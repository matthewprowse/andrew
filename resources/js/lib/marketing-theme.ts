export const TAILWIND_COLOR_OPTIONS = Object.entries(TAILWIND_PALETTE).flatMap(
    ([name, shades]) =>
        Object.entries(shades).map(
            ([shade, hex]) => [`${name}-${shade}`, hex] as const,
        ),
);

const PALETTE_DISPLAY_SHADES = {
    50: 1,
    200: 2,
    500: 3,
    700: 4,
    950: 5,
} as const;

export const PALETTE_OPTIONS = TAILWIND_COLOR_OPTIONS.filter(([name]) =>
    Object.keys(PALETTE_DISPLAY_SHADES).some((shade) =>
        name.endsWith(`-${shade}`),
    ),
).map(([name, hex]) => {
    const [family, shade] = name.split('-');
    return {
        name,
        hex,
        label: `${titleCase(family)} ${PALETTE_DISPLAY_SHADES[shade as unknown as keyof typeof PALETTE_DISPLAY_SHADES]}`,
    };
});

export function titleCase(value: string): string {
    return value.replace(
        /(^|[- ])([a-z])/g,
        (_, prefix: string, letter: string) =>
            `${prefix === '-' ? ' ' : prefix}${letter.toUpperCase()}`,
    );
}

